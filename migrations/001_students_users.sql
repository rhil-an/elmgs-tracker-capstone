-- PostgreSQL foundation only. Apply to a dedicated empty demo database.
-- Application login and JSON storage do not use these tables yet.

CREATE TABLE students (
    student_id TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    nationality TEXT NOT NULL,
    faculty TEXT,
    programme TEXT,
    study_mode TEXT,
    learner_intake TEXT,
    candidature_date DATE,
    candidature_period TEXT,
    preliminary_research_proposal DATE,
    supervisor_appointment DATE,
    research_seminar DATE,
    proposal_defence DATE,
    ethics_clearance DATE,
    final_draft_submission DATE,
    viva_voce DATE,
    visa_expiry DATE,
    last_check_in DATE,
    current_location TEXT CHECK (current_location IN ('Local', 'Overseas')),
    sample_compliance_status TEXT,
    postgraduate_stay_start_date DATE,
    postgraduate_stay_required_completion_date DATE
);

CREATE TABLE users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL CHECK (btrim(password_hash) <> ''),
    role TEXT NOT NULL CHECK (role IN ('student', 'admin')),
    student_id TEXT UNIQUE REFERENCES students(student_id) ON DELETE RESTRICT,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (email = lower(btrim(email)) AND email <> ''),
    CHECK ((role = 'student' AND student_id IS NOT NULL)
        OR (role = 'admin' AND student_id IS NULL))
);

-- TEXT accommodates hashes generated by PHP now and after algorithm upgrades.
-- Do not insert plaintext passwords or password fields in audit records.
